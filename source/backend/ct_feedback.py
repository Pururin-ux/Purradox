def _by_number(rows):
    return {f"{'A' if i < 10 else 'B'}{i + 1 if i < 10 else i - 9}": row for i, row in enumerate(rows)}


FORMS = {"demo": DEMO, "01": _by_number(VARIANT_1), "02": _by_number(VARIANT_2), "03": _by_number(DIAGNOSTIC)}


def feedback_for(form, task, given, correct):
    row = FORMS.get(form, {}).get(task["id"])
    if not row:
        return {}
    title, prompt, *details = row
    figure, notes, caption = (details + [None] * 3)[:3]
    guide = {"title": title}
    if figure:
        guide["figure"] = figure
    if caption:
        guide["caption"] = caption
    if correct:
        return guide
    note = None
    if notes and task["kind"] == "number":
        try:
            note = notes.get(float(str(given).replace("−", "-").replace(",", ".")))
        except ValueError:
            pass
    if notes and task["kind"] != "number":
        chosen = given if isinstance(given, list) else [given]
        for index in chosen:
            if type(index) is int and 1 <= index <= len(task["options"]):
                note = notes.get(task["options"][index - 1])
                if note:
                    break
    return {**guide, "note": note or prompt}
