def choice(lesson, level, text, options, answer, solution):
    return {"lessonSlug": lesson, "part": "A", "level": level, "text": text,
            "kind": "multi" if isinstance(answer, list) else "single",
            "options": options, "answer": answer, "solution": [{"text": step} for step in solution]}


def number(lesson, level, text, unit, answer, expression, solution):
    return {"lessonSlug": lesson, "part": "B", "level": level, "kind": "number",
            "text": text, "unit": unit, "answer": answer, "solution": [{"text": step} for step in solution],
            "audit": {"expression": expression, "expected": answer, "unit": unit}}


